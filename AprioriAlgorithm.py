def cal_support(transactions, itemset):
  itemset = set(itemset)
  count = 0
  if transactions:
    for transaction in transactions:
        if itemset.issubset(transaction):
            count += 1
  else:return 0
  return count / len(transactions)

def generate_level1(transactions , min_support):
  items = set()
  for transaction in transactions:
    for item in transaction:
      items.add(item)
  level1 = {}
  for(item) in items:
    itemset =  tuple(sorted({item}))
    support = cal_support(transactions, itemset)
    if(support >= min_support):
      level1[tuple(sorted(itemset))] = support
  return level1

def jioning_sets(previus_list , k):
  jion_set = set()
  n = len(previus_list)
  for(i) in range(n):
    for(j) in range(i+1 , n):
      joined_itemset = tuple(sorted(set(previus_list[i]) | set(previus_list[j])))
      if(len(joined_itemset) == k):
        jion_set.add(joined_itemset)
  return jion_set

def prunuing_candidate(candidates, previus_list):
    prun_candidates = set()
    previus_freq = set(previus_list)
    for candidate in candidates:
        valid = True
        for item in candidate:
            subset = tuple(x for x in candidate if x != item)

            if subset not in previus_freq:
                valid = False
                break
        if valid:
            prun_candidates.add(candidate)
    return prun_candidates
def generating_freq_sets(transactions , min_support):
  levels = {}
  level_1 = generate_level1(transactions , min_support)
  if not level_1:
    return levels
  levels[1] = level_1
  previus_list = list(level_1.keys())
  k = 2
  while True:
    candidates = jioning_sets(previus_list , k)
    prun_candidates = prunuing_candidate(candidates , previus_list)
    level = {}
    for candidate in prun_candidates:
      support = cal_support(transactions , candidate)
      if(support >= min_support):
        level[candidate] = support
    if not level:
      break
    levels[k] = level
    #previus_list.append(candidate)
    previus_list = list(level.keys())

    k += 1
  return levels

