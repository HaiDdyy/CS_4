def calcLift(transactions, itemset_A, itemset_B):
    sup_A = cal_support(transactions, itemset_A)
    sup_B = cal_support(transactions, itemset_B)
    sup_AB = cal_support(
        transactions, set(itemset_A) | set(itemset_B)
    )
    if sup_A == 0 or sup_B == 0:
        return 0
    lift = sup_AB / (sup_A * sup_B)
    return lift

def calcAllLifts(transactions, levels):
    frequent_itemsets = []
    for level in levels.values():
        frequent_itemsets.extend(level.keys())
    lift_results = {}
    for itemset in frequent_itemsets:
      for antecedent, consequent in generate_association_rule(itemset):
              antecedentValue=tuple(sorted(antecedent))
              consequentValue=tuple(sorted(consequent))
              lift = calcLift(transactions, antecedentValue, consequentValue)
              lift_results[(antecedentValue, consequentValue)] = lift
    
    return lift_results

def interpret_lift(lift):
    if lift > 1:
        return "Positive Association"
    elif lift == 1:
        return "Independent"
    else:
        return "Negative Association"


