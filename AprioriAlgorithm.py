# generating possible multiple combinations 
def generate_association_rule(items):
  rules=[]
  n = len(items)

  for mask in range(1 ,2**n - 1):
    antecedent = set()

    for i in range(n):
        if mask & (1 << i):
            antecedent.add(items[i])

    consequent = set(items) - antecedent
    rules.append((antecedent,consequent))
  return rules


