def associationRules(levels, transactions, min_confidence=0.5, min_support=0.4):
    rules = []

    for level, itemsets in levels.items():
        for itemset, support in itemsets.items():

            # itemsets can be a single string or a tuple
            items = [itemset] if isinstance(itemset, str) else list(itemset)

            # need at least 2 items to make a rule
            if len(items) < 2:
                continue
            # try every possible antecedent (all proper subsets)
            for antecedent, consequent in generate_association_rule(items):

                ant_support = cal_support(transactions, antecedent)
                if ant_support == 0:
                    continue

                confidence = support / ant_support

                if confidence >= min_confidence and support >= min_support:
                    rules.append({
                        "antecedent": tuple(antecedent),
                        "consequent": tuple(consequent),
                        "support": support,
                        "confidence": confidence,
                    })

    return rules


def show_rules(rules):
    for i, r in enumerate(rules, 1):
        print(f"{i}. {r['antecedent']} -> {r['consequent']} "
              f"| Support: {r['support']:.2f} "
              f"| Confidence: {r['confidence']:.2f}")

